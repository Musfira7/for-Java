class arith_op {
    public static void main(String[] args)
    {
        int a = 15, b = 7;
        System.out.println("Sum = "+(a+b));
        System.out.println("Sub = "+(a-b));
        System.out.println("multiply = "+(a*b));
        System.out.println("Division = "+(a/b));
        System.out.println("Modulus = "+(a%b));

    }
}